"""Generate RESULTS.md from results/*.json (no hand-typed numbers).
Usage: python -m scripts.write_results
"""
import json
from pathlib import Path

R = Path("results")


def j(p):
    f = R / p
    return json.loads(f.read_text(encoding="utf-8")) if f.exists() else None


def ci(x):
    return f"[{x[0]:.2e}, {x[1]:.2e}]"


def main():
    P, T, D, S = j("radar_params.json"), j("cfar_theory.json"), j("cfar_pfa_diagnostic.json"), j("scenes.json")
    V, M, Y, VV = j("rtl_verification.json"), j("rtl_mutation_test.json"), j("synth_yosys.json"), j("synth_vivado.json")
    A, C = j("hw_agreement.json"), j("classify.json")
    L = []
    a = L.append
    a("# Results (simulation and tool reports only)\n")
    a("Generated by `scripts/write_results.py` from `results/*.json`. Data are simulated; the RTL is verified in "
      "simulation; resource and timing numbers are synthesis/implementation tool reports, not hardware measurements.\n")

    w = P["detection_waveform"]
    cd = P["classification_dwell"]
    a("## 1. Radar\n")
    a(f"24 GHz FMCW, 250 MHz, 100 µs chirps, {w['range_bins']} complex samples, {w['doppler_bins']} chirps: range "
      f"resolution {w['range_resolution_m']:.2f} m, max range {w['max_range_m']:.1f} m, ±{w['max_unambiguous_velocity_mps']:.1f} m/s, "
      f"velocity resolution {w['velocity_resolution_mps']:.2f} m/s. Micro-Doppler classification dwell: {cd['prf_Hz'] / 1e3:.0f} kHz PRF, "
      f"±{cd['max_unambiguous_velocity_mps']:.0f} m/s unambiguous (blade tips in the data up to {cd['max_blade_tip_speed_mps_in_dataset']:.0f} m/s).\n")

    a("## 2. CFAR theory checks (1D CA-CFAR, N = 32, guard 2)\n")
    a("| Noise | design Pfa | measured | 95% CI | inside CI |\n|---|---|---|---|---|")
    for key, lab in (("pfa_iid", "i.i.d. exponential"), ("pfa_chain_rect", "full chain, rectangular window"),
                     ("pfa_chain", "full chain, Hann window")):
        for r in T[key]:
            a(f"| {lab} | {r['design']:.0e} | {r['measured']:.3e} | {ci(r['ci95'])} | {'yes' if r['design_inside_ci'] else 'no'} |")
    a("")
    hann = T["pfa_chain"]
    a(f"- **Hann windowing raises the false-alarm rate {min(r['measured'] / r['design'] for r in hann):.1f}–"
      f"{max(r['measured'] / r['design'] for r in hann):.1f}x above design** through the full chain; rectangular windows match "
      "the design. The window correlates neighbouring range cells, so the training cells are less independent than CA-CFAR assumes.")
    if D:
        a(f"- The i.i.d. 1e-3 point outside its CI was rechecked with 10x the cells and 3 new seeds: "
          + ", ".join(f"{r['measured']:.3e} (inside: {r['inside']})" for r in D["runs"]) + ". It was a fluctuation, not a bias.")
    for k, lab in (("swerling0", "Swerling 0 (numerical theory)"), ("swerling1", "Swerling 1 (closed form)")):
        v = T["pd"][k]
        a(f"- Pd vs SNR, {lab}: theory inside the 95% CI at {sum(x['theory_inside_ci'] for x in v)}/{len(v)} SNR points, "
          f"max |sim − theory| = {max(abs(x['pd_sim'] - x['pd_theory']) for x in v):.4f} ({v[0]['trials']:,} trials per point).")
    a("")

    a("## 3. Detection in hard conditions\n")
    e, pr = S["edge"], S["pair"]
    g = lambda kind, o: next(x["pd"] for x in e["pd"][kind] if x["offset"] == o)
    a(f"- **Clutter edge (+15 dB):** a target 2–4 cells on the LOW side of the edge is masked: Pd CA {g('CA', -2):.2f}/{g('CA', -4):.2f}, "
      f"OS {g('OS', -2):.2f}/{g('OS', -4):.2f} (far from the edge ≈ {g('CA', -20):.2f}). False alarms per cell at the edge cell: "
      f"CA {e['fa_vs_distance']['CA']['0']:.4f}, OS {e['fa_vs_distance']['OS']['0']:.4f} (design 1e-4). Further from the edge OS "
      f"degrades more gracefully (10 cells out: CA {g('CA', -10):.2f}, OS {g('OS', -10):.2f}), but with k = 24/32 neither survives "
      "the last few cells before the edge.")
    sep = lambda kind, s: next(x["pd"] for x in pr["pd_first"][kind] if x["separation"] == s)
    a(f"- **Two close targets:** with the second target inside the training window (separation 8 cells) Pd of the first is "
      f"CA {sep('CA', 8):.2f} vs OS {sep('OS', 8):.2f} (single target: CA {pr['pd_single']['CA']:.2f}, OS {pr['pd_single']['OS']:.2f}). "
      "OS-CFAR is robust to an interfering target; CA-CFAR is not.")
    ctl = S["control_noise_only"]
    a(f"- **Noise-only control:** false-alarm clusters per frame CA-1D {ctl['CA-1D']['false_alarm_clusters_per_frame']:.1f}, "
      f"OS-1D {ctl['OS-1D']['false_alarm_clusters_per_frame']:.1f}, CA-2D {ctl['CA-2D']['false_alarm_clusters_per_frame']:.1f} "
      f"(design: {ctl['CA-1D']['design_expected_false_cells_per_frame']:.1f} false cells/frame).")
    a("- **Drone in K-distributed ground clutter (CNR 30 dB per sample):**\n")
    a("| body SNR | suppression | detector | Pd | false-alarm clusters / frame |\n|---|---|---|---|---|")
    for k, v in S["scene"].items():
        snr, c, d = k.split("|")
        if snr in ("10", "20"):
            a(f"| {snr} dB | {c} | {d} | {v['pd']:.2f} | {v['false_alarms_per_frame']:.1f} |")
    a(f"\n{S['frames_per_snr']} frames per SNR; every detector and suppression option sees the same frames.\n")

    a("## 4. CFAR hardware block (rtl/cfar_ca_1d.v)\n")
    a(f"- **Bit-exact with the Python fixed-point model on all {V['n_tests']} tests** ({V['total_decisions']:,} decisions, "
      f"{V['total_cells']:,} cells): directed (zeros, spikes, close spikes, clutter edge, full-scale values, alpha extremes, "
      "line-length boundaries), random lines with and without input stalls, and range lines from simulated scenes; "
      "(N_TRAIN, N_GUARD) = (8,2), (16,2), (32,4). Simulator: " + V["simulator"] + ".")
    nonequiv = [m for m in M["mutants"] if not m["equivalent"]]
    a(f"- **Mutation test:** {sum(m['caught'] for m in nonequiv)}/{len(nonequiv)} non-equivalent RTL mutants caught; "
      "1 equivalent mutant (an always-zero sum bit) correctly produces no difference.")
    a(f"- **Fixed vs float CFAR on realistic frames:** {A['agreement_rate'] * 100:.2f}% decision agreement "
      f"({A['diff']} of {A['decisions']:,} differ: {A['diff_saturation']} from input saturation, {A['diff_flooring']} from "
      f"input flooring, {A['diff_alpha_quant']} from alpha quantization; quantized alpha changes Pfa to "
      f"{A['pfa_with_quantized_alpha']:.4e}).\n")
    a("| N_TRAIN | Yosys LUT | Yosys FF | Yosys SRL | Yosys DSP48 | Vivado LUT | Vivado FF | Vivado DSP | Vivado Fmax est. |")
    a("|---|---|---|---|---|---|---|---|---|")
    vv = {r["n_train"]: r for r in VV["results"]} if VV else {}
    for r in Y["results"]:
        q = vv.get(r["n_train"], {})
        a(f"| {r['n_train']} | {r['LUT']} | {r['FF']} | {r['SRL']} | {r['DSP48']} | {q.get('LUT', '—')} | {q.get('FF', '—')} | "
          f"{q.get('DSP48E1', '—')} | {q.get('fmax_estimate_MHz', '—')} MHz |")
    a(f"\nYosys: {Y['tool'].split('(')[0].strip()}, `synth_xilinx -family xc7` (open-source estimate, no timing). "
      + (f"Vivado: {VV['tool']}, {VV['part']}, out-of-context synthesis + place & route, 4.0 ns target "
         f"(not met; Fmax = 1/(period − WNS)); tool report, not a board measurement." if VV else "") + "\n")

    if C:
        a("## 5. Micro-Doppler drone vs bird\n")
        a(f"{C['n_instances']} instances × {C['slices_per_instance']} slices = {C['n_spectrograms']} spectrograms; TinyCNN "
          f"{C['cnn_params']:,} parameters; 3 training seeds.\n")
        a("| Split | CNN float32 acc. | CNN INT8 (sim.) acc. | features + LR acc. | CNN macro F1 |\n|---|---|---|---|---|")
        lab = {"leaky": "random-slice (LEAKY)", "instance": "by instance (primary)", "heldout": "held-out configuration"}
        for s in ("leaky", "instance", "heldout"):
            d = C["splits"][s]
            f = lambda k: f"{d[k]['accuracy_mean']:.3f} ± {d[k]['accuracy_std']:.3f}"
            a(f"| {lab[s]} | {f('cnn_f32')} | {f('cnn_int8')} | {f('features_lr')} | "
              f"{d['cnn_f32']['macro_f1_mean']:.3f} ± {d['cnn_f32']['macro_f1_std']:.3f} |")
        gap = C["splits"]["leaky"]["cnn_f32"]["accuracy_mean"] - C["splits"]["instance"]["cnn_f32"]["accuracy_mean"]
        gapo = C["splits"]["instance"]["cnn_f32"]["accuracy_mean"] - C["splits"]["heldout"]["cnn_f32"]["accuracy_mean"]
        a(f"\nLeaky − instance accuracy gap (CNN): {gap * 100:+.1f} points; instance − held-out-configuration gap: "
          f"{gapo * 100:+.1f} points. Held out: drones with rotor rates 100–120 rev/s and birds with flap rates 8–10 Hz "
          "(training saw < 100 rev/s and < 8 Hz).\n")
        bands = C["splits"]["instance"]["cnn_f32"]["per_seed"][0]["acc_by_snr"]
        import numpy as np
        a("CNN accuracy by body SNR per pulse (instance split, mean of seeds): " + ", ".join(
            f"{b} dB: {np.mean([p['acc_by_snr'][b] for p in C['splits']['instance']['cnn_f32']['per_seed']]):.2f}" for b in bands) + ".\n")

    a("## 6. What this does NOT show\n")
    a("- Real radar data, real drones or birds: all data are simulated point-scatterer models.")
    a("- Hardware behaviour: the RTL ran in simulation only; resources and Fmax are tool reports.")
    a("- Performance of a complete radar: no tracking, no antenna/beam model, no multipath, no RCS model beyond "
      "point scatterers with fixed amplitude ratios.")
    a("- The INT8 classifier is simulated by fake quantization, not run as an integer kernel.")
    Path("RESULTS.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("RESULTS.md written")


if __name__ == "__main__":
    main()
